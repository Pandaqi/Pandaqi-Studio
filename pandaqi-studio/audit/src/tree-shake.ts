/* How much of pq-games ends up in a bundle depends on what you import.
 *
 *   cd pandaqi-studio/audit
 *   bun run tree-shake
 *
 * Bundles a few small entry points with esbuild (minified, browser target) and writes
 * audit/tree-shaking.md. The size of the barrel is the "everything" reference; the component
 * entries are what a game that only needs sprites pays.
 */

import { existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const auditDir = resolve(import.meta.dir, "..");
const studioDir = resolve(auditDir, "..");
const outDir = join(studioDir, "audit-artifacts", "tree-shake");
const workDir = join(outDir, "entries");
const libDir = join(studioDir, "assets", "lib", "pq-games");
const reportPath = join(auditDir, "tree-shaking.md");

interface Entry
{
    id: string
    label: string
    note: string
    code: string
}

const ENTRIES:Entry[] = [
    {
        id: "barrel",
        label: "`import * from \"lib/pq-games\"`",
        note: "the full library (what every game page imports today)",
        code: `import * as pq from "lib/pq-games";\n(globalThis as any).__pq = pq;\n`,
    },
    {
        id: "geometry-only",
        label: "`lib/pq-games/geometry/vector2`",
        note: "one pure geometry module",
        code: `import { Vector2 } from "lib/pq-games/geometry/vector2";\n(globalThis as any).__pq = new Vector2();\n`,
    },
    {
        id: "drawer-sprite",
        label: "drawer + transform + sprite",
        note: "the smallest realtime drawer a sprite game needs",
        code: `import { createCanvasDrawer } from "lib/pq-games/draw/canvasDrawer";
import { transformComponent } from "lib/pq-games/draw/components/transform";
import { spriteComponent } from "lib/pq-games/draw/components/sprite";
const drawer = createCanvasDrawer(null, [transformComponent, spriteComponent]);
(globalThis as any).__pq = drawer;
`,
    },
    {
        id: "drawer-full",
        label: "`lib/pq-games/draw` (all presets)",
        note: "the realtime layer including text, shapes, containers and the GPU batch",
        code: `import * as draw from "lib/pq-games/draw";\n(globalThis as any).__pq = draw;\n`,
    },
    {
        id: "sprite-component",
        label: "sprite component alone",
        note: "a single component, for measuring the floor",
        code: `import { spriteComponent } from "lib/pq-games/draw/components/sprite";\n(globalThis as any).__pq = spriteComponent;\n`,
    },
    {
        id: "webgpu-batch",
        label: "`WebGPUSpriteBatch` alone",
        note: "the GPU path without the canvas components",
        code: `import { WebGPUSpriteBatch } from "lib/pq-games/draw/webgpu/spriteBatch";\n(globalThis as any).__pq = WebGPUSpriteBatch;\n`,
    },
];

const aliasPlugin = {
    name: "pq-games-alias",
    setup(build:any)
    {
        build.onResolve({ filter: /^lib\/pq-games($|\/)/ }, (args:any) =>
        {
            const sub = args.path.slice("lib/pq-games".length).replace(/^\//, "");
            if(!sub) { return { path: join(libDir, "index.ts") }; }
            if(sub.endsWith(".ts")) { return { path: join(libDir, sub) }; }
            if(existsSync(join(libDir, sub))) { return { path: join(libDir, sub, "index.ts") }; }
            return { path: join(libDir, `${sub}.ts`) };
        });
    },
};

const main = async () =>
{
    rmSync(workDir, { recursive: true, force: true });
    mkdirSync(workDir, { recursive: true });

    const rows:{ id:string, label:string, note:string, bytes:number }[] = [];

    for(const entry of ENTRIES)
    {
        const entryPath = join(workDir, entry.id + ".ts");
        writeFileSync(entryPath, entry.code, "utf8");

        const result = await Bun.build({
            entrypoints: [entryPath],
            outdir: join(workDir, entry.id + "-out"),
            naming: "bundle.js",
            target: "browser",
            format: "iife",
            minify: true,
            sourcemap: "none",
            plugins: [aliasPlugin],
        });

        if(!result.success)
        {
            for(const log of result.logs) { console.error(entry.id, String(log)); }
            process.exit(2);
        }

        const bytes = (await Bun.file(join(workDir, entry.id + "-out", "bundle.js")).arrayBuffer()).byteLength;
        rows.push({ id: entry.id, label: entry.label, note: entry.note, bytes });
        console.log(`${entry.id.padEnd(18)} ${(bytes / 1024).toFixed(1)} KiB`);
    }

    const barrel = rows.find((row) => row.id === "barrel");
    const sprite = rows.find((row) => row.id === "drawer-sprite");
    const component = rows.find((row) => row.id === "sprite-component");
    const kb = (bytes:number) => (bytes / 1024).toFixed(1) + " KiB";

    const markdown = `# Tree-shaking — pq-games

Generated by \`bun run tree-shake\`. Minified, browser-target IIFE bundles (esbuild via \`Bun.build\`),
each using what it imports so nothing is dropped by accident.

| entry | imports | size |
| --- | --- | --- |
${rows.map((row) => `| ${row.id} | ${row.label} | ${kb(row.bytes)} |`).join("\n")}

${barrel && sprite ? `A sprite-only drawer bundles to **${kb(sprite.bytes)}** instead of **${kb(barrel.bytes)}** for the whole library${component ? ` (a single component is ${kb(component.bytes)})` : ""}.` : ""}

## How to read this

- The barrel (\`lib/pq-games\`) is the historical entry point. It pulls geometry, layout, settings,
  tools, PDF export, all renderers and the realtime layer, because a game page may use any of them.
  Its own side effects live in \`setup.ts\` (the \`structuredClone\` fallback and the \`PQ_GAMES\` marker),
  so importing a part directly skips them.
- Every module under \`draw/\` is side-effect free and imports only what it needs: \`matrix.ts\` imports
  nothing, \`components/sprite.ts\` imports \`measure.ts\`, and neither pulls the document pipeline.
- Bundlers drop unused exports from a barrel only when the modules are side-effect free. The entries
  above import directly, which is the reliable path; use \`lib/pq-games/draw/...\` in a realtime game.
`;

    writeFileSync(reportPath, markdown, "utf8");
    console.log(`\nreport: ${reportPath}`);
}

main().catch((error) => { console.error("tree-shake: internal error", error); process.exit(3); });
